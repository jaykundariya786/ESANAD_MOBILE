export const getCountryCategory = countryName => {
  if (!countryName) return null;
  if (countryName === 'United States') return 'USA';
  if (SCHENGEN_COUNTRIES.includes(countryName)) return 'Schengen';
  if (ASIA_COUNTRIES.includes(countryName)) return 'Asia';
  if (OCEANIA_COUNTRIES.includes(countryName)) return 'Oceania';
  if (countryName.startsWith('Worldwide')) return 'Worldwide';
  return 'Worldwide'; // Default or other
};
